// Grip offsets from the center of the original 512px role frame. Mirrored directions share the same poses.
const standing = [[16,-27],[12,-23],[5,-18],[-9,-18],[-16,-23]];
const running = [
  [[19,-43],[19,-47],[18,-49],[18,-47],[19,-43],[20,-30],[20,-24],[20,-23],[20,-23],[20,-23],[20,-25],[20,-31]],
  [[24,-36],[25,-40],[25,-43],[24,-43],[24,-35],[20,-23],[13,-20],[11,-22],[12,-22],[12,-22],[12,-22],[18,-23]],
  [[21,-28],[24,-32],[26,-35],[25,-34],[22,-27],[8,-18],[-2,-24],[-11,-22],[-14,-22],[-14,-22],[-8,-22],[7,-18]],
  [[6,-25],[10,-26],[12,-29],[13,-27],[8,-22],[-6,-16],[-16,-21],[-20,-25],[-24,-27],[-24,-27],[-19,-23],[-9,-18]],
  [[-14,-23],[-13,-26],[-11,-27],[-11,-26],[-13,-21],[-19,-20],[-22,-30],[-23,-35],[-22,-36],[-23,-35],[-22,-30],[-19,-20]]
];
export function handAnchor(dir: number, frame: string, moving: boolean) {
  const step = Number(frame.slice(-8,-4));
  return moving ? running[dir][step] ?? standing[dir] : standing[dir];
}
